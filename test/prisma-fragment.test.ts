import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import { assetCoreMigrate } from '../src/migrate.js';
import {
  buildPrismaFragment,
  corePrismaFragment,
  findBackRelations,
  PrismaFragmentError,
} from '../src/prisma-fragment.js';
import { checkPrismaDrift, parseUnsupportedFields } from '../src/testing/drift.js';
import { createTestDatabase, type TestDatabase } from './support/db.js';
import { DATASOURCE_HEADER, getDmmf, prismaValidate } from './support/prisma.js';

const APP = `
model AuditEntry {
  id       String @id @default(dbgenerated("uuidv7()")) @db.Uuid
  tenantId String @map("tenant_id") @db.Uuid
  tenant   Tenant @relation("AuditEntryTenant", fields: [tenantId], references: [id], onDelete: Restrict, onUpdate: NoAction)

  @@map("audit_entry")
  @@schema("platform")
}

model Credential {
  userId String      @id @map("user_id") @db.Uuid
  user   UserAccount @relation("CredentialUser", fields: [userId], references: [id], onDelete: Cascade, onUpdate: NoAction)

  @@map("credential")
  @@schema("platform")
}
`;

describe('Prisma fragment (prisma/core.prisma)', () => {
  it('validates with the real Prisma CLI, including injected back-relations of app models', async () => {
    const fragment = buildPrismaFragment([APP]);
    expect(fragment).toMatch(/^\/\/ GENERATED by `asset-core prisma-fragment`/);
    expect(fragment).toContain('auditEntryTenant');
    expect(fragment).toMatch(/credentialUser\s+Credential\? @relation\("CredentialUser"\)/);
    const out = await prismaValidate({
      'schema.prisma': DATASOURCE_HEADER,
      'core.prisma': fragment,
      'app.prisma': APP,
    });
    expect(out).toMatch(/valid/);
  }, 120_000);

  it('reads Unsupported("…") fields, which the DMMF omits', () => {
    const text = `model RetentionPolicy {\n  id String @id\n  retainFor Unsupported("interval") @map("retain_for")\n  extra Unsupported("tsrange")?\n}\n`;
    expect(parseUnsupportedFields(text).get('RetentionPolicy')).toEqual([
      { column: 'retain_for', type: 'interval', optional: false },
      { column: 'extra', type: 'tsrange', optional: true },
    ]);
  });

  it('requires app → core relations to be named', () => {
    const unnamed = APP.replace('@relation("AuditEntryTenant", ', '@relation(');
    expect(() => findBackRelations([unnamed])).toThrow(PrismaFragmentError);
  });

  it('the embedded copy is current (pnpm embed)', () => {
    expect(() =>
      execFileSync(process.execPath, [
        join(import.meta.dirname, '..', 'scripts', 'embed-migrations.mjs'),
        '--check',
      ]),
    ).not.toThrow();
  });

  describe('matches the SQL migrations (structural drift check)', () => {
    let db: TestDatabase;
    const dmmf = getDmmf([
      ['schema.prisma', DATASOURCE_HEADER],
      ['core.prisma', corePrismaFragment()],
    ]);
    const check = () =>
      checkPrismaDrift(db.admin, dmmf, {
        schemas: ['core'],
        schemaText: corePrismaFragment(),
        ignoreTables: ['core._migration'],
      });

    beforeAll(async () => {
      db = await createTestDatabase('ac_drift');
      await assetCoreMigrate({ client: db.admin });
    });
    afterAll(async () => {
      await db.drop();
    });

    it('no drift between core.prisma and the migrated database', async () => {
      expect(await check()).toEqual([]);
    });

    it('detects drift (an extra column, a missing index, a changed default)', async () => {
      await db.admin.query('BEGIN');
      try {
        await db.admin.query(`ALTER TABLE core.unit ADD COLUMN extra text`);
        await db.admin.query(`DROP INDEX core.unit_floor_id_idx`);
        await db.admin.query(`ALTER TABLE core.tenant ALTER COLUMN timezone SET DEFAULT 'UTC'`);
        await db.admin.query(`DROP INDEX core.unit_ownership_party_id_idx`);
        await db.admin.query(
          `CREATE INDEX unit_ownership_party_id_idx ON core.unit_ownership (party_id DESC)`,
        );
        const problems = await check();
        expect(problems).toEqual(
          expect.arrayContaining([
            expect.stringContaining('core.unit.extra'),
            expect.stringContaining('unit_floor_id_idx'),
            expect.stringContaining('core.tenant.timezone: default UTC'),
            expect.stringContaining('unit_ownership_party_id_idx: column party_id is DESC in the database'),
          ]),
        );
      } finally {
        await db.admin.query('ROLLBACK');
      }
    });
  });
});
