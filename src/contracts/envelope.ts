import { z } from 'zod';

import { IsoDateTime, SourcePlatform, Uuid } from './common.js';

/**
 * Integration event envelope (D-153, schema-design v2 §4.8, blueprint "Integration contracts"). Every event
 * exchanged between getproperty, getbuild and getpack is persisted by both sides in
 * `bridge.integration_event` (UQ(platform, direction, idempotency_key)) and acknowledged within 24 h.
 * Compatibility: additive changes only within a major version; consumers ignore unknown fields (objects are
 * parsed non-strict, unknown keys are stripped).
 */
export const EnvelopeBase = z.object({
  /** uuidv7 generated by the producer; also the outbox / domain event id on the producing side. */
  eventId: Uuid,
  /** Event type, e.g. "unit.transferred". */
  type: z.string().regex(/^[a-z]+(\.[a-z_]+)+$/),
  /** Payload schema version of this event type (integer, bumped only by a new major of the package). */
  version: z.number().int().min(1),
  occurredAt: IsoDateTime,
  /** Stable per business fact, e.g. "getproperty:service_request:<uuid>:reported" — consumers dedupe on it. */
  idempotencyKey: z.string().min(8).max(300),
  sourcePlatform: SourcePlatform,
  /** The producing tenant in the source platform (getbuild developer tenant, getproperty tenant). */
  tenantId: Uuid.nullable(),
  correlationId: Uuid.optional(),
  causationId: Uuid.optional(),
});
export type EnvelopeBase = z.infer<typeof EnvelopeBase>;

/** Builds the envelope schema of one event type around its payload schema. */
export function eventEnvelope<T extends string, P extends z.ZodType>(type: T, payload: P, version = 1) {
  return EnvelopeBase.extend({
    type: z.literal(type),
    version: z.literal(version),
    payload,
  });
}
