#!/usr/bin/env node
// Embeds migrations/*.sql and prisma/core.prisma into src/generated/assets.ts so the runner and the CLI
// need no file-system lookups (works the same from dist/esm, dist/cjs and when bundled).
//   node scripts/embed-migrations.mjs          rewrite src/generated/assets.ts
//   node scripts/embed-migrations.mjs --check  exit 1 when the committed file is stale (CI, build)
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const files = readdirSync(join(root, 'migrations'))
  .filter((f) => /^\d{4}_[a-z0-9_]+\.sql$/.test(f))
  .sort();
const migrations = files.map((file) => {
  const sql = readFileSync(join(root, 'migrations', file), 'utf8').replace(/\r\n/g, '\n');
  return { id: file.replace(/\.sql$/, ''), checksum: createHash('sha256').update(sql).digest('hex'), sql };
});
const corePrisma = readFileSync(join(root, 'prisma', 'core.prisma'), 'utf8').replace(/\r\n/g, '\n');

const out = `// GENERATED by scripts/embed-migrations.mjs from migrations/*.sql and prisma/core.prisma — do not edit.
// Regenerate with \`pnpm embed\`; \`pnpm build\` and the test suite fail when this file is stale.
/* eslint-disable */

export const PACKAGE_NAME = ${JSON.stringify(pkg.name)};
export const PACKAGE_VERSION = ${JSON.stringify(pkg.version)};

export interface EmbeddedMigration {
  /** File name without .sql, e.g. "0001_extensions_helpers". Applied in this order. */
  readonly id: string;
  /** sha256 (hex) of the SQL text with LF line endings. */
  readonly checksum: string;
  readonly sql: string;
}

export const MIGRATIONS: readonly EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)};

export const CORE_PRISMA: string = ${JSON.stringify(corePrisma)};
`;

const target = join(root, 'src', 'generated', 'assets.ts');
if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== out) {
    console.error('src/generated/assets.ts is stale: run `pnpm embed` and commit the result.');
    process.exit(1);
  }
  process.exit(0);
}
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`embedded ${migrations.length} migrations and core.prisma (${pkg.name}@${pkg.version})`);
